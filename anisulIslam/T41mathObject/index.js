console.log(Math.sqrt(16)); // square root of 16
console.log(Math.pow(2, 3)); // 2 to the power of 3
console.log(Math.max(5, 10, 3)); // maximum of the numbers
console.log(Math.min(5, 10, 3)); // minimum of the numbers
console.log(Math.abs(-7)); // absolute value of -7 
console.log(Math.sin(2)); // sine of 2 radians
console.log(Math.floor(7.8)); // floor method returns the largest integer less than or equal to a given number
console.log(Math.ceil(7.2)); // ceiling method returns the smallest integer greater than or equal to a given number 
console.log(Math.round(7.5)); // round method returns the value of a number rounded to the nearest integer, <.5 reaturns down, >=.5 returns up 

console.log(Math.random()); // random number between 0 and 1
console.log(Math.random()*5); // random number between 0 and 5
console.log(Math.floor(Math.random()*5)); // random integer between 0 and 4
console.log(Math.floor(Math.random()*5)+1); // random integer between 1 and 5
console.log(Math.floor(Math.random()*11)+10); // random integer between 10 and 20